import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';
import { SecretDisplay } from '../frontend/secret-display.js';

class RedesignSmoke {
  host = new UiTestHost();
  errors = [];
  external = [];
  click = async selector => this.page.locator(selector).getByRole('button').click();
  field = async (id, value) => this.page.locator('#' + id).getByRole('textbox').fill(value);
  api = async (url, body) => {
    const response = await fetch(this.base + url, body === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.ok(response.ok, url + ' ' + response.status);
    return response.json();
  };

  run = async () => {
    const key = 'lower <ключ>.[x]';
    const alias = '$${<' + key + '>}';
    const display = new SecretDisplay([{ key, alias, realValue: 'synthetic secret' }]);
    assert.equal(display.counts({ content: alias + ' ' + alias }).get(key), 2);
    assert.match(display.render(alias), /data-hint-only/);
    assert.doesNotMatch(display.render(alias), /token-copy|synthetic secret/);
    await this.host.init();
    this.base = await this.host.app.listen({ port: 0, host: '127.0.0.1' });
    this.browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
    const context = await this.browser.newContext({ viewport: { width: 1440, height: 900 } });
    await this.host.isolateClipboard(context);
    await context.route('**/*', route => {
      if (route.request().url().startsWith(this.base)) return route.continue();
      this.external.push(route.request().url());
      return route.abort();
    });
    this.page = await context.newPage();
    this.page.setDefaultTimeout(15000);
    this.page.on('pageerror', error => this.errors.push(error.message));
    await this.page.goto(this.base + '/dashboard');
    await this.page.waitForFunction(() => window.app?.events);
    assert.equal(await this.page.locator('#navConnectionsBtn, #firstRunGuide, #overviewMetrics').count(), 0);
    assert.equal((await this.api('/api/workspace')).visible.length, 0);
    await this.click('[data-action="route-create"]');
    await this.page.locator('[data-action="route-template"]').filter({ hasText: 'OpenAI' }).click();
    assert.equal(await this.page.locator('#connectionCreateDialog').evaluate(node => node.open), true);
    assert.equal((await this.api('/api/workspace')).visible.length, 0);
    assert.equal((await this.api('/api/routes')).length, 5);
    assert.equal(await this.page.locator('#connectionName').getByRole('textbox').inputValue(), 'OpenAI');
    assert.equal(await this.page.locator('#connectionUpstream').getByRole('textbox').inputValue(), 'https://api.openai.com/v1');
    assert.equal(await this.page.locator('#connectionPrefix, #connectionSuffix, #connectionSettingsSuffix').count(), 0);
    assert.equal(await this.page.locator('#existingConnectionsSection').count(), 0);
    await this.page.locator('#connectionForm').getByRole('button', { name: 'Добавить', exact: true }).click();
    await this.page.waitForFunction(() => !document.getElementById('connectionCreateDialog').open);
    const firstId = (await this.api('/api/workspace')).selected;
    assert.equal(firstId, 'openai');
    assert.equal((await this.api('/api/routes')).find(route => route.id === firstId).prefix, 'openai');
    assert.deepEqual((await this.api('/api/workspace')).visible, [firstId]);
    await this.click('[data-action="route-settings"]');
    await this.field('connectionSettingsName', 'My connection');
    await this.page.locator('#connectionSettingsForm').getByRole('button', { name: 'Сохранить', exact: true }).click();
    await this.page.waitForFunction(() => !document.getElementById('connectionSettingsDialog').open);
    assert.equal((await this.api('/api/routes')).find(route => route.id === firstId).name, 'My connection');
    await this.page.getByRole('button', { name: 'Добавить соединение', exact: true }).click();
    await this.field('connectionUpstream', 'https://synthetic.invalid/v1');
    await this.field('connectionName', 'alpha');
    await this.field('connectionName', 'alpha-team');
    await this.page.locator('#connectionForm').getByRole('button', { name: 'Добавить', exact: true }).click();
    await this.page.waitForFunction(() => !document.getElementById('connectionCreateDialog').open);
    assert.equal((await this.api('/api/workspace')).visible.length, 2);
    const secondId = (await this.api('/api/workspace')).selected;
    assert.equal((await this.api('/api/routes')).find(route => route.id === secondId).name, 'alpha-team');
    assert.equal(await this.page.locator('#connectionBar [role="tab"]').count(), 2);
    assert.equal(await this.page.locator('#activeConnection').count(), 0);
    assert.deepEqual(await this.page.locator('#connectionBar [role="tab"]').allTextContents(), ['My connection', 'alpha-team']);
    assert.equal((await this.api('/api/routes')).find(route => route.id === firstId).suffix, '');
    assert.equal((await this.api('/api/routes')).find(route => route.id === secondId).suffix, '');
    await this.page.locator('#connectionBar [role="tab"]').first().click();
    await this.page.waitForFunction(id => document.getElementById('connection-tab-' + id)?.getAttribute('aria-selected') === 'true', firstId);
    assert.equal((await this.api('/api/workspace')).selected, firstId);
    await this.page.keyboard.press('End');
    await this.page.waitForFunction(id => document.getElementById('connection-tab-' + id)?.getAttribute('aria-selected') === 'true', secondId);
    await this.page.reload();
    await this.page.waitForFunction(() => window.app?.events);
    assert.equal(await this.page.locator('#connection-tab-' + secondId).getAttribute('aria-selected'), 'true');
    await this.click('[data-action="route-open"]');
    assert.equal(await this.page.locator('#connectionHelpKind').count(), 0);
    assert.doesNotMatch(await this.page.locator('#connectionSettingsDialog').innerText(), /Python|SDK|PowerShell/);
    const secondRoute = (await this.api('/api/routes')).find(route => route.id === secondId);
    assert.ok((await this.page.locator('#connectionSettingsDialog').innerText()).includes('/' + secondRoute.prefix));
    assert.doesNotMatch(secondRoute.prefix, /synthetic/);
    await this.click('[data-settings-close]');
    await this.click('#navSecretsBtn');
    await this.page.reload();
    await this.page.waitForFunction(() => window.app?.events);
    assert.equal(new URL(this.page.url()).hash, '#secrets');
    assert.equal(await this.page.locator('#viewSecrets').isVisible(), true);
    await this.click('#openAddModalBtn');
    await this.field('modalKeyInput', key);
    await this.field('modalValInput', 'synthetic secret');
    await this.click('#cancelModalBtn');
    await this.click('#openAddModalBtn');
    assert.equal(await this.page.locator('#modalValInput').getByRole('textbox').inputValue(), 'synthetic secret');
    await this.page.locator('#secretForm').getByRole('button', { name: 'Сохранить секрет', exact: true }).click();
    await this.page.waitForFunction(() => !document.getElementById('secretModal').open);
    const hint = this.page.locator('#manualTableBody gv-hint').filter({ hasText: alias }).first();
    await hint.locator('[data-hint-only]').click();
    assert.equal(await hint.evaluate(node => node.readState().pinned), true);
    assert.equal(await hint.locator('[data-hint-only]').getAttribute('aria-expanded'), 'true');
    assert.equal(await this.page.evaluate(() => navigator.clipboard.readText()), '');
    await this.page.keyboard.press('Escape');
    await this.click('[data-action="secret-copy"]');
    assert.equal(await this.page.evaluate(() => navigator.clipboard.readText()), alias);
    const exportData = await this.api('/api/export?group=secrets&id=' + encodeURIComponent(key));
    assert.equal(exportData.data.secrets.length, 1);
    assert.equal(exportData.data.secrets[0].real_value, 'synthetic secret');
    const fullExport = await this.api('/api/export');
    assert.ok(fullExport.data.proxy[0].host);
    assert.equal(fullExport.data.connections.length, 6);
    await this.click('#exportAllBtn');
    const choices = this.page.locator('#exportDialog input[type="checkbox"]');
    assert.equal(await choices.count(), 5);
    for (const choice of await choices.all()) await choice.uncheck();
    assert.equal(await this.page.locator('#exportDialog [data-download]').getByRole('button').isDisabled(), true);
    await this.page.locator('#exportDialog input[value="patterns"]').check();
    await this.page.locator('#exportDialog input[value="secrets"]').check();
    const downloaded = this.page.waitForEvent('download');
    await this.click('#exportDialog [data-download]');
    const saved = JSON.parse(await readFile(await (await downloaded).path(), 'utf8'));
    assert.deepEqual(Object.keys(saved.data).sort(), ['patterns', 'secrets']);
    assert.equal(saved.data.secrets[0].real_value, 'synthetic secret');
    assert.equal(await this.page.locator('[data-action="export-open"]').count(), 0);
    const stamp = new Date().toISOString();
    this.host.database.upsertSession('saved-conversation', 'Fixture client');
    this.host.database.saveTransaction({ id: 'legacy-call', session_id: 'saved-conversation', client: 'Fixture client', method: 'POST', url: '/openai/v1/chat/completions', status: 200, latency_ms: 5, prompt_text: 'original-only', masked_prompt: '', model_response: 'answer', intercepted_secrets: '[]', timestamp: stamp });
    const legacy = await this.api('/api/sessions/saved-conversation');
    assert.equal(legacy[0].maskedPrompt, undefined);
    assert.equal(legacy[0].targetProvider ?? null, null);
    await this.click('#navOverviewBtn');
    await this.page.evaluate(() => window.app.overview.refresh());
    assert.match(await this.page.locator('#overviewConversation').innerText(), /представление запроса не сохранено/);
    await this.click('#navSecretsBtn');
    await this.page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await this.page.locator('#manualVaultTable').evaluate(node => node.scrollWidth <= node.clientWidth + 1), true);
    await this.click('#navRulesBtn');
    assert.equal(await this.page.locator('#rulesList gv-details').count(), 0);
    assert.equal(await this.page.locator('#rulesList').getByRole('heading', { name: 'Любой IP-адрес', exact: true }).count(), 1);
    const toggle = this.page.locator('[data-pattern-toggle]').first();
    const before = await toggle.isChecked();
    await toggle.click();
    await this.page.waitForFunction(value => document.querySelector('[data-pattern-toggle]').checked !== value, before);
    await this.click('#navFeedBtn');
    await this.page.evaluate(() => window.app.feed.addEvent({ id: 'unknown-fixture', type: 'custom-event', details: {} }));
    assert.equal(await this.page.locator('#liveFeedContainer').getByRole('heading', { name: 'Неизвестное приложение · Событие шлюза' }).count(), 1);
    assert.deepEqual(this.errors, []);
    assert.deepEqual(this.external, []);
    console.log('PASS: isolated redesign workflows, drafts, lowercase/unrestricted tokens, clipboard, navigation, responsive table, export and truthful events');
  };

  close = async () => { await this.browser?.close(); await this.host.close(); };
}

const smoke = new RedesignSmoke();
try { await smoke.run(); } finally { await smoke.close(); }
