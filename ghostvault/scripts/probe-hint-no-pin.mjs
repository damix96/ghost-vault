import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const errors = [];
const writes = [];
const external = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url());
  if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
});
try {
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length > 0);
  const action = page.locator('#overviewRoutes [data-action="route-open"]').first();
  await action.evaluate(element => { element.hint = 'Изолированный пример подсказки для проверки публичной опции закрепления.'; });
  const primary = action.getByRole('button', { name: 'Как подключить', exact: true });
  const originalControl = await primary.elementHandle();
  const hint = action.locator('gv-hint');
  let activations = 0;
  await page.exposeFunction('recordPrimaryActivation', () => { activations++; });
  await action.evaluate(element => element.addEventListener('gv-activate', () => window.recordPrimaryActivation()));
  await primary.hover();
  await page.waitForFunction(() => document.querySelector('#overviewRoutes [data-action="route-open"] gv-hint').readState().mode === 'preview');
  await action.getByRole('tooltip').waitFor();
  assert.equal(await hint.getByRole('button').count(), 1, 'Preview contains only the original action button');
  assert.equal(await page.getByRole('button', { name: 'Закрепить подсказку', exact: true }).count(), 0);
  assert.equal(await action.evaluate(element => element.hintPinButton), false);
  assert.equal(await action.getAttribute('hint-pin-button'), null);
  await action.evaluate(element => { element.hintPinButton = true; });
  await action.getByRole('button', { name: 'Закрепить подсказку', exact: true }).click();
  assert.equal(await hint.evaluate(element => element.readState().pinned), true);
  assert.equal(activations, 0, 'Opt-in pin must not activate the primary action');
  await action.evaluate(element => { element.hintPinButton = false; });
  assert.equal(await hint.evaluate(element => element.readState().pinned), true);
  assert.equal(await primary.evaluate((element, original) => element === original, originalControl), true);
  await hint.getByRole('button', { name: 'Закрыть подсказку', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#overviewRoutes [data-action="route-open"]').contains(document.activeElement));
  await primary.press('F1');
  assert.equal(await hint.evaluate(element => element.readState().pinned), true);
  await hint.getByRole('button', { name: 'Закрыть подсказку', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#overviewRoutes [data-action="route-open"]').contains(document.activeElement));
  await page.getByRole('button', { name: 'Обновить страницу', exact: true }).focus();
  await primary.focus();
  await page.waitForFunction(() => document.querySelector('#overviewRoutes [data-action="route-open"] gv-hint').readState().mode === 'preview');
  await primary.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Закрепить подсказку', exact: true }).count(), 0);
  await primary.click();
  await page.getByRole('dialog').waitFor();
  assert.equal(activations, 1);
  await page.getByRole('button', { name: 'Закрыть инструкцию', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: 'Как читать пояснения к кнопкам', exact: true }).count(), 0);
  assert.doesNotMatch(await page.locator('body').innerText(), /Закрепить подсказку/);
  assert.deepEqual(writes, []);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  const report = { isolated: true, preview_pin_button: false, explicit_optin_pin_button_works: true, runtime_false_preserves_pinned_and_primary: true, optin_pin_primary_activations: 0, hover: true, focus: true, primary_activations: activations, F1_close_Escape: true, meta_hint_guide_absent: true, isolated_hint_text_fixture: true, api_writes: writes, external_requests: external, page_errors: errors };
  if (process.env.NO_PIN_REPORT) await writeFile(process.env.NO_PIN_REPORT, JSON.stringify(report, null, 2));
  console.log('PASS default no pin button; explicit opt-in still works without primary; hover/focus/primary once/F1 close; zero writes or external requests');
} finally {
  await browser.close();
  await host.close();
}
