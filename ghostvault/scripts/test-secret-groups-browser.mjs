import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

class SecretGroupsBrowserCheck {
  host = new UiTestHost();
  out = resolve('.cache/grouping-evidence');
  checks = [];
  errors = [];
  group = prefix => this.page.locator('[data-secret-group="' + prefix + '"]');
  card = key => this.page.locator('#autoTableBody [data-secret-record="' + key + '"]');
  open = prefix => this.group(prefix).evaluate(node => node.open);
  refresh = () => this.page.evaluate(() => window.app.fetchData(true));
  unfocus = () => this.page.locator('#searchInput').focus();
  count = (prefix, total) => this.page.waitForFunction(({ prefix, total }) => [...document.querySelectorAll('[data-secret-group]')].find(node => node.dataset.secretGroup === prefix)?.querySelector('.app-secret-group-count').textContent === 'Записей: ' + total, { prefix, total });
  seed = key => this.vault.setAutoSecret(key, 'synthetic-value-' + key);

  run = async () => {
    process.env.UI_BUILD_DIR ||= resolve('.cache/grouping-ui');
    await mkdir(this.out, { recursive: true });
    await this.host.init();
    this.vault = this.host.server.getVault();
    const keys = ['FIX_123_321', 'FIX_123_333', 'FIX_232_333', 'FIX_232_553', 'FIX_121_222', 'FIX_456_455'];
    keys.forEach(this.seed);
    this.vault.setManualSecret('MANUAL_ONE', 'synthetic-manual-value');
    this.vault.setManualSecret('ENCRYPTED_ONE', 'synthetic-encrypted-value', undefined, true);
    const aliases = this.vault.getAutoSecrets().map(entry => [entry.key, entry.alias]);
    this.base = await this.host.app.listen({ host: '127.0.0.1', port: 0 });
    this.browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const context = await this.browser.newContext({ viewport: { width: 1440, height: 1080 } });
    await this.host.isolateClipboard(context);
    this.page = await context.newPage();
    this.page.on('pageerror', error => this.errors.push(error.message));
    await this.page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    await this.page.goto(this.base + '/dashboard');
    await this.page.waitForFunction(() => window.app?.autoSecrets.length === 6);
    await this.page.locator('#navSecretsBtn').click();
    await this.page.locator('#subTabAutoBtn').click();
    assert.deepEqual(await this.page.locator('#autoTableBody > *').evaluateAll(nodes => nodes.map(node => node.dataset.secretGroup || node.dataset.secretRecord)), ['FIX_123', 'FIX_232', 'FIX_121_222', 'FIX_456_455']);
    assert.equal(await this.page.locator('[data-secret-group][open]').count(), 0);
    await this.page.screenshot({ path: this.out + '/exact-six-desktop.png', fullPage: true });
    const summary = this.group('FIX_123').locator('summary').first();
    await summary.focus(); await this.page.keyboard.press('Enter');
    assert.equal(await this.open('FIX_123'), true);
    await this.page.keyboard.press('Space');
    assert.equal(await this.open('FIX_123'), false);
    await this.page.keyboard.press('Enter'); await this.page.keyboard.press('Tab');
    assert.equal(await this.card('FIX_123_321').evaluate(node => node.contains(document.activeElement)), true);
    this.checks.push('exact6case flat groups-first/singles order, initially closed, native Enter/Space/Tab');
    await this.page.locator('#searchInput').fill('321');
    await this.count('FIX_123', '1 из 2');
    assert.equal(await this.open('FIX_123'), true);
    assert.equal(await this.group('FIX_123').locator('[data-secret-record]').count(), 1);
    await this.group('FIX_123').locator('summary').first().click();
    assert.equal(await this.open('FIX_123'), false);
    await this.page.locator('#searchInput').fill('');
    await this.count('FIX_123', 2);
    assert.equal(await this.open('FIX_123'), true);
    assert.equal(await this.open('FIX_232'), false);
    await this.page.locator('#searchInput').fill('FIX_232');
    assert.equal(await this.open('FIX_232'), true);
    await this.page.locator('#searchInput').fill('');
    assert.equal(await this.open('FIX_232'), false);
    this.checks.push('membership from full dataset, matched/total, temporary search opening and exact base-state restoration');
    await this.page.evaluate(() => {
      const token = document.createElement('button'); token.id = 'groupNavigationFixture'; token.dataset.secretKey = 'FIX_232_333'; token.textContent = 'Synthetic token target';
      document.getElementById('viewSecrets').prepend(token);
    });
    await this.page.locator('#groupNavigationFixture').click({ modifiers: ['Control'] });
    await this.page.waitForFunction(() => document.activeElement?.dataset.secretRecord === 'FIX_232_333');
    await this.page.locator('#groupNavigationFixture').evaluate(node => node.remove());
    assert.equal(await this.open('FIX_232'), true);
    assert.equal(await this.card('FIX_232_333').locator('details').evaluate(node => node.open), false);
    this.seed('FIX_232_VARYINGLENGTH');
    await this.refresh();
    assert.equal(await this.group('FIX_232').locator('[data-secret-record]').count(), 2);
    await this.unfocus(); await this.count('FIX_232', 3);
    this.checks.push('actual Ctrl+token navigation reveals parent/focuses exact row without revealing value; focused refresh defers and flushes');
    await this.page.evaluate(() => {
      const node = document.querySelector('[data-secret-record="FIX_232_333"] h3');
      const range = document.createRange(); range.selectNodeContents(node); window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
    });
    this.seed('FIX_232_X'); await this.refresh();
    assert.equal(await this.group('FIX_232').locator('[data-secret-record]').count(), 3);
    await this.page.evaluate(() => window.getSelection().removeAllRanges());
    await this.count('FIX_232', 4);
    const hint = this.card('FIX_232_333').locator('gv-hint').first();
    await hint.locator('[data-hint-only]').click();
    assert.equal(await hint.evaluate(node => node.readState().pinned), true);
    this.seed('FIX_232_LAST'); await this.refresh();
    assert.equal(await this.group('FIX_232').locator('[data-secret-record]').count(), 4);
    await this.page.evaluate(() => document.activeElement?.blur());
    assert.equal(await this.group('FIX_232').locator('[data-secret-record]').count(), 4);
    await hint.evaluate(node => node.hide());
    await this.count('FIX_232', 5);
    this.checks.push('selection and pinned hint independently defer latest update, release flushes without another fetch');
    const alias = aliases.find(([key]) => key === 'FIX_123_321')[1];
    await this.card('FIX_123_321').locator('.app-record-details > summary').click();
    const copy = this.card('FIX_123_321').locator('gv-copy').last();
    await copy.locator('button').click();
    assert.equal(await this.page.evaluate(() => navigator.clipboard.readText()), alias);
    await this.unfocus();
    const promote = await fetch(this.base + '/api/vault/promote', { method: 'POST', headers: { Origin: this.base, 'Content-Type': 'application/json' }, body: JSON.stringify({ key: 'FIX_123_321' }) });
    assert.equal(promote.status, 200); await this.refresh();
    assert.equal(await this.group('FIX_123').count(), 0);
    assert.equal(await this.page.locator('#autoTableBody > [data-secret-record="FIX_123_333"]').count(), 1);
    assert.equal(this.vault.getManualSecrets().find(entry => entry.key === 'FIX_123_321').alias, alias);
    this.vault.deleteSecret('FIX_123_333'); await this.refresh();
    assert.equal(await this.card('FIX_123_333').count(), 0);
    this.checks.push('individual copy exact/clipboard isolated; real promote dissolves group to full singleton with unchanged alias; deletion removes singleton');
    const long = 'LONG_PREFIX_' + 'N'.repeat(78);
    [long + '_A', long + '_BB', 'FIX_RAND_RAND', 'FIX_RAND_X', 'NO_SEPARATOR', '_EDGE', 'EDGE_'].forEach(this.seed);
    await this.refresh(); await this.unfocus();
    assert.equal(await this.group('FIX_RAND').count(), 1);
    assert.equal(await this.group('FIX').count(), 0);
    await this.group(long).locator('summary').first().click(); await this.unfocus();
    for (const width of [390, 320]) {
      await this.page.setViewportSize({ width, height: 900 });
      await this.page.screenshot({ path: this.out + '/groups-mobile-' + width + '.png', fullPage: true });
      assert.equal(await this.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      assert.equal(await this.group(long).locator('summary').first().evaluate(node => node.scrollWidth <= node.clientWidth), true);
    }
    await this.page.setViewportSize({ width: 1440, height: 1080 });
    await this.page.screenshot({ path: this.out + '/groups-expanded-desktop.png', fullPage: true });
    this.checks.push('arbitrary suffix lengths, full long prefixes, no parent FIX;320/390px no horizontal overflow');
    await this.page.locator('#subTabManualBtn').click();
    assert.equal(await this.page.locator('#manualTableBody [data-secret-group]').count(), 0);
    const encrypted = this.page.locator('#manualTableBody [data-secret-record="ENCRYPTED_ONE"]');
    assert.equal(await encrypted.locator('gv-copy').count(), 2);
    await this.page.evaluate(() => window.app.preferences.setPrivacy(true));
    assert.equal(await encrypted.locator('gv-copy').count(), 1);
    assert.equal(await encrypted.innerHTML().then(html => html.includes('synthetic-encrypted-value')), false);
    await this.page.evaluate(() => window.app.preferences.setPrivacy(false));
    assert.equal(await encrypted.locator('gv-copy').count(), 2);
    this.checks.push('actual encrypted storage fixture: original-display and hidden-display API modes retain previous value/copy behavior; manual list stays flat');
    await this.page.evaluate(() => {
      const app = window.app; const key = 'MANUAL_ONE'; const row = document.querySelector('[data-secret-record="' + key + '"]'); row.focus();
      const entries = app.manualSecrets.map(entry => entry.key === key ? { ...entry, realValue: 'synthetic-pending-must-clear' } : entry);
      app.renderer.renderManualRows(entries, '');
      app.manualSecrets = app.manualSecrets.map(entry => entry.key === key ? { ...entry, isSecret: true, realValue: undefined, variants: undefined, representations: undefined } : entry);
      app.renderer.replaceManualRows(app.manualSecrets, '');
    });
    await this.unfocus();
    assert.equal(await this.page.evaluate(() => window.app.renderer.pending.has('manualTableBody')), false);
    assert.equal(await this.page.locator('#manualTableBody').innerText().then(text => text.includes('synthetic-pending-must-clear')), false);
    assert.equal(await this.page.locator('#manualTableBody [data-secret-record="MANUAL_ONE"] gv-copy').count(), 1);
    this.checks.push('ordinary manual ungrouped; explicit projected-protected fixture force-clears pending render and old original/copy, alias copy retained');
    assert.deepEqual(this.errors, []);
    const hash = createHash('sha256').update(await readFile(resolve(process.env.UI_BUILD_DIR, 'index.html'))).digest('hex');
    await writeFile(this.out + '/result.json', JSON.stringify({ status: 'PASS', checks: this.checks, errors: this.errors, runtime: process.version, browser: this.browser.version(), stage: process.env.UI_BUILD_DIR, indexSha256: hash, clipboard: 'isolated', encryptedFixture: 'real native-provider record and current interface modes; extra client safe projection for forced pending purge; no broad crypto suite' }, null, 2));
    console.log('PASS grouped browser acceptance: ' + this.checks.length + ' groups; real staged UI/source API fixtures; no page errors');
  };
  close = async () => { await this.browser?.close(); await this.host.close(); };
}
const check = new SecretGroupsBrowserCheck();
try { await check.run(); } catch (error) {
  await writeFile(check.out + '/failure.json', JSON.stringify({ error: error.message, checks: check.checks, pageErrors: check.errors }, null, 2));
  await check.page?.screenshot({ path: check.out + '/failure.png', fullPage: true });
  throw error;
} finally { await check.close(); }
