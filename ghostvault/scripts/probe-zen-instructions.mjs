import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
await host.isolateClipboard(context);
const page = await context.newPage();
page.setDefaultTimeout(10000);
const writes = [];
const external = [];
const errors = [];
page.on('request', request => {
  if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.method() + ' ' + new URL(request.url()).pathname);
  if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
});
page.on('pageerror', error => errors.push(error.message));
const read = async path => (await fetch(base + path)).json();
const paths = ['/api/routes', '/api/patterns', '/api/vault', '/api/sessions'];
const initial = await Promise.all(paths.map(read));
try {
  const zen = initial[0].find(route => new URL(route.cliUrl || route.incomingUrl).pathname === '/opencode/v1');
  const generic = initial[0].find(route => route.id !== zen?.id);
  assert.ok(zen && generic, 'Both existing preset instruction paths must be exercised');
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length > 0);
  assert.match(await page.locator('#firstRunGuide').innerText(), /Нажмите «Как подключить»/);
  const open = async route => {
    const actions = page.locator('#overviewRoutes [data-action="route-open"]');
    const index = (await actions.evaluateAll(nodes => nodes.map(node => JSON.parse(node.dataset.args)[0]))).indexOf(route.id);
    await actions.nth(index).getByRole('button', { name: 'Как подключить', exact: true }).click();
    await page.getByRole('dialog', { name: 'Подключить приложение · ' + route.name, exact: true }).waitFor();
  };
  await open(zen);
  const dialog = page.locator('#connectionSettingsDialog');
  if (process.env.ZEN_INSTRUCTIONS_START_SCREENSHOT) await page.getByRole('dialog', { name: 'Подключить приложение · ' + zen.name, exact: true }).screenshot({ path: process.env.ZEN_INSTRUCTIONS_START_SCREENSHOT });
  assert.doesNotMatch(await dialog.ariaSnapshot(), /plugin|PowerShell|Python/);
  await dialog.getByRole('button', { name: 'Пример для одной модели', exact: true }).click();
  await dialog.getByRole('button', { name: 'Скопировать настройку модели', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  const native = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.deepEqual(native, { providers: { opencode: { models: { 'deepseek-v4.1-flash': { settings: { baseURL: zen.cliUrl || zen.incomingUrl } } } } } });
  await dialog.getByRole('button', { name: 'Отдельное подключение ghostvault-zen', exact: true }).click();
  await dialog.getByRole('button', { name: 'Проверка отдельного подключения', exact: true }).click();
  const text = await dialog.innerText();
  assert.doesNotMatch(text, /Одного изменения Base URL недостаточно/);
  assert.match(text, /DeepSeek V4.1 Flash/);
  assert.match(text, /остальные настройки и записи сохраните/);
  assert.match(text, /opencode models --standalone/);
  assert.match(text, /ghostvault-zen\/deepseek-v4.1-flash/);
  assert.match(text, /Выбор платной модели остаётся ручным/);
  assert.doesNotMatch(text, /Other →|apiKey.*public|--pure|--auto/);
  await dialog.getByRole('button', { name: 'Скопировать фрагмент plugins', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  const config = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.deepEqual(Object.keys(config), ['plugins']);
  assert.equal(config.plugins.length, 1);
  assert.equal(config.plugins[0].package, 'file:///E:/projects/aegis-gate/ghostvault/opencode/zen-connection');
  assert.deepEqual(config.plugins[0].options, { baseURL: zen.cliUrl || zen.incomingUrl, nativeTransport: false });
  await dialog.getByRole('button', { name: 'Адрес CLI → VAULT', exact: true }).click();
  await dialog.getByRole('button', { name: 'Скопировать адрес CLI → VAULT', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Бесплатные модели и relay', exact: true }).click();
  await dialog.getByText(/работа всех бесплатных моделей не гарантируется/i).waitFor();
  assert.match(await dialog.innerText(), /nativeTransport: false.*true/s);
  await dialog.getByRole('button', { name: 'Границы проверки', exact: true }).click();
  await dialog.getByText(/Вспомогательные модели могут выбираться отдельно/).waitFor();
  if (process.env.ZEN_INSTRUCTIONS_SCREENSHOT) await page.screenshot({ path: process.env.ZEN_INSTRUCTIONS_SCREENSHOT, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByRole('button', { name: 'Скопировать фрагмент plugins', exact: true }).scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  const code = dialog.locator('gv-details[data-detail-id="zen-alias.' + zen.id + '"] pre.app-code').first();
  const geometry = await code.boundingBox();
  assert.ok(geometry.x >= 0 && geometry.x + geometry.width <= 391, 'Configuration stays within mobile viewport');
  if (process.env.ZEN_INSTRUCTIONS_MOBILE_SCREENSHOT) await page.screenshot({ path: process.env.ZEN_INSTRUCTIONS_MOBILE_SCREENSHOT });
  await dialog.getByRole('button', { name: 'Закрыть инструкцию', exact: true }).click();
  await page.waitForFunction(() => !window.app.connections.editor.isOpen());
  await open(generic);
  assert.match(await dialog.innerText(), /Задайте переменную окружения и запустите Claude Code/);
  assert.equal(await dialog.getByRole('button', { name: 'Скопировать фрагмент plugins', exact: true }).count(), 0);
  assert.deepEqual(await Promise.all(paths.map(read)), initial);
  assert.deepEqual(writes, []);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  if (process.env.ZEN_INSTRUCTIONS_REPORT) await writeFile(process.env.ZEN_INSTRUCTIONS_REPORT, JSON.stringify({ isolated: true, api_writes: writes, state_unchanged: true, clipboard: 'browser-memory double', native_model_config_copied: true, optional_plugin_config_copied: true, generic_path_distinct: true, paid_free_limits_visible: true, desktop_mobile: true, external_requests: external, page_errors: errors }, null, 2));
  console.log('PASS Zen native model override plus optional alias, explicit paid/free limits, mobile and clean isolated state');
} catch (error) {
  console.error(await page.locator('body').ariaSnapshot());
  throw error;
} finally {
  await browser.close();
  await host.close();
}
