import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
await host.isolateClipboard(context);
const page = await context.newPage();
page.setDefaultTimeout(10000);
const errors = [];
const external = [];
const writes = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
  if (request.method() === 'POST') writes.push({ path: new URL(request.url()).pathname, body: request.postDataJSON() });
});
const press = label => page.getByRole('button', { name: label, exact: true }).click();
const field = id => page.locator('#' + id).getByRole('textbox');
const read = async path => (await fetch(base + path)).json();
try {
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length > 0);
  await press('Подключения');
  await press('Добавить другой сервис');
  await field('connectionUpstream').fill('models.synthetic.invalid/v1');
  await field('connectionUpstream').press('Enter');
  await page.getByText(/Нужен полный URL с http/).waitFor();
  assert.equal(writes.length, 0);
  for (const value of ['ftp://models.synthetic.invalid/v1', 'https://models.synthetic.invalid/v1?key=demo', 'https://user:demo@models.synthetic.invalid/v1', 'https://models.synthetic.invalid/v1#demo']) {
    await field('connectionUpstream').fill(value);
    await press('Сохранить подключение');
    assert.ok(await page.locator('#connectionUpstream').evaluate(element => element.error));
    assert.equal(writes.length, 0);
  }
  await field('connectionUpstream').fill('https://models.synthetic.invalid/v1');
  await page.locator('#connectionPreview').getByText(/models-synthetic-invalid\/v1/).waitFor();
  const automaticPreview = await page.locator('#connectionPreview').innerText();
  assert.doesNotMatch(automaticPreview, /<путь>|<имя>/);
  if (process.env.FORM_ROUTE_SCREENSHOT) await page.screenshot({ path: process.env.FORM_ROUTE_SCREENSHOT });
  await field('connectionUpstream').press('Enter');
  await page.locator('#createConnection').waitFor({ state: 'hidden' });
  let routes = await read('/api/routes');
  const automatic = routes.find(route => (route.upstreamUrl || route.targetUrl) === 'https://models.synthetic.invalid/v1');
  assert.equal(automatic.name, 'models.synthetic.invalid');
  assert.match(automatic.cliUrl || automatic.incomingUrl, /\/models-synthetic-invalid\/v1$/);
  assert.ok(automaticPreview.includes(automatic.cliUrl || automatic.incomingUrl));
  await press('Добавить другой сервис');
  await field('connectionUpstream').fill('https://models.synthetic.invalid/v1');
  await page.locator('#connectionPreview').getByText(/models-synthetic-invalid-2\/v1/).waitFor();
  await press('Выбрать своё имя в адресе');
  for (const invalid of ['my/service', base + '/my-service/v1']) {
    await field('connectionPrefix').fill(invalid);
    const count = writes.length;
    await press('Сохранить подключение');
    await page.getByText(/без полного URL, внутренних слешей и \/v1/).last().waitFor();
    assert.equal(writes.length, count);
    assert.equal(await field('connectionPrefix').inputValue(), invalid);
  }
  await field('connectionPrefix').fill('/Custom-Endpoint/');
  await field('connectionName').fill('Мой тестовый сервер');
  await press('Сохранить подключение');
  await page.locator('#createConnection').waitFor({ state: 'hidden' });
  routes = await read('/api/routes');
  assert.ok(routes.some(route => route.name === 'Мой тестовый сервер' && (route.cliUrl || route.incomingUrl).endsWith('/custom-endpoint/v1')));
  const custom = routes.find(route => route.name === 'Мой тестовый сервер');
  const actions = page.locator('#connectionsList [data-action="route-open"]');
  const index = (await actions.evaluateAll(nodes => nodes.map(node => JSON.parse(node.dataset.args)[0]))).indexOf(custom.id);
  await actions.nth(index).getByRole('button', { name: 'Как подключить', exact: true }).click();
  await press('Изменить адрес сервиса модели');
  await field('connectionSettingsTarget').fill('https://models.synthetic.invalid/v1?demo=1');
  let count = writes.length;
  await press('Сохранить адрес сервиса');
  assert.ok(await page.locator('#connectionSettingsTarget').evaluate(element => element.error));
  assert.equal(writes.length, count);
  await field('connectionSettingsTarget').fill('http://127.0.0.1:45678/v1/');
  await page.route('**/api/routes/' + custom.id, route => route.request().method() === 'POST' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'synthetic unavailable' }) }) : route.continue());
  await press('Сохранить адрес сервиса');
  await page.getByText(/Не удалось подтвердить сохранение: synthetic unavailable/).waitFor();
  assert.equal(await field('connectionSettingsTarget').inputValue(), 'http://127.0.0.1:45678/v1/');
  await page.unroute('**/api/routes/' + custom.id);
  await press('Сохранить адрес сервиса');
  await page.getByRole('dialog', { name: 'Подключить приложение · Мой тестовый сервер', exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await read('/api/routes')).find(route => route.id === custom.id).upstreamUrl, 'http://127.0.0.1:45678/v1');
  await press('Секреты');
  await press('Добавить секрет');
  await field('modalKeyInput').fill('');
  const raw = '  synthetic value\n';
  await field('modalValInput').fill(raw);
  count = writes.length;
  await press('Сохранить секрет');
  await page.getByText('Введите имя, например DB_HOST.', { exact: true }).waitFor();
  assert.equal(writes.length, count);
  await field('modalKeyInput').fill('db_host');
  await field('modalKeyInput').press('Home');
  await field('modalKeyInput').press('ArrowRight');
  await field('modalKeyInput').pressSequentially('-');
  assert.equal(await field('modalKeyInput').inputValue(), 'd-b_host');
  assert.equal(await field('modalKeyInput').evaluate(input => input.selectionStart), 2);
  await press('Сохранить секрет');
  await page.getByRole('dialog', { name: 'Добавить секрет', exact: true }).waitFor({ state: 'hidden' });
  const vault = await read('/api/vault');
  assert.equal((vault.manualSecrets || vault.manual).find(secret => secret.key === 'd-b_host').realValue, raw);
  await press('Добавить секрет');
  await field('modalKeyInput').fill('d-b_host');
  await field('modalValInput').fill('other synthetic value');
  count = writes.length;
  await press('Сохранить секрет');
  await page.getByText(/Такое имя уже существует/).waitFor();
  assert.equal(writes.length, count);
  await press('Отмена');
  await page.locator('#manualTableBody').getByRole('button', { name: 'Изменить', exact: true }).click();
  assert.equal(await field('modalKeyInput').getAttribute('readonly'), '');
  await field('modalValInput').fill(raw + 'updated');
  await press('Сохранить секрет');
  await page.getByRole('dialog', { name: 'Изменить секрет', exact: true }).waitFor({ state: 'hidden' });
  const editedVault = await read('/api/vault');
  const editedSecrets = editedVault.manualSecrets || editedVault.manual;
  assert.equal(editedSecrets.length, 1);
  assert.equal(editedSecrets[0].key, 'd-b_host');
  assert.equal(editedSecrets[0].realValue, raw + 'updated');
  await press('Правила');
  await press('Добавить правило');
  await field('patternNameInput').fill('Учебное правило');
  await field('patternRegexInput').fill('[');
  count = writes.length;
  await press('Создать и включить правило');
  await page.getByText(/Выражение не разбирается как JavaScript regex/).waitFor();
  assert.equal(await field('patternRegexInput').inputValue(), '[');
  assert.equal(writes.length, count);
  await field('patternRegexInput').fill(' DEMO_[A-Z0-9]{8} ');
  if (process.env.FORM_RULE_SCREENSHOT) await page.getByRole('dialog', { name: 'Новое правило автообнаружения', exact: true }).screenshot({ path: process.env.FORM_RULE_SCREENSHOT });
  await press('Создать и включить правило');
  await page.getByRole('dialog', { name: 'Новое правило автообнаружения', exact: true }).waitFor({ state: 'hidden' });
  const pattern = (await read('/api/patterns')).find(item => item.name === 'Учебное правило');
  assert.equal(pattern.type, 'custom');
  assert.equal(pattern.pattern, ' DEMO_[A-Z0-9]{8} ');
  assert.ok(pattern.enabled);
  await page.setViewportSize({ width: 390, height: 844 });
  await press('Подключения');
  await press('Добавить другой сервис');
  await field('connectionUpstream').fill('https://models.synthetic.invalid/v1');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  const mobileName = await page.locator('#connectionsList').getByText('Мой тестовый сервер', { exact: true }).boundingBox();
  assert.ok(mobileName.width >= 150 && mobileName.height < 100, 'Custom connection title must retain readable width beside multiple actions');
  await page.locator('gv-hint').evaluateAll(hints => hints.forEach(hint => hint.hide()));
  await page.locator('#toast').waitFor({ state: 'hidden' });
  if (process.env.FORM_MOBILE_SCREENSHOT) await page.screenshot({ path: process.env.FORM_MOBILE_SCREENSHOT, fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  assert.deepEqual(await read('/api/sessions'), []);
  if (process.env.FORM_CLARITY_REPORT) await writeFile(process.env.FORM_CLARITY_REPORT, JSON.stringify({ isolated: true, automatic_route_preview_matches_saved: true, manual_prefix_retained: true, full_url_and_internal_slash_blocked: true, edge_slash_normalized: true, raw_secret_preserved: true, key_text_and_caret_preserved: true, existing_key_not_renamed: true, duplicate_secret_protected: true, regex_error_inline: true, regex_whitespace_preserved: true, default_type_custom: true, desktop_mobile: true, cloud_requests: external, page_errors: errors, synthetic_api_writes: writes.length, sessions: [] }, null, 2));
  console.log('PASS focused forms: generated route, manual prefix errors, exact secret, duplicate guard, regex correction, mobile, no cloud');
} catch (error) {
  console.error(await page.locator('body').ariaSnapshot());
  throw error;
} finally {
  await browser.close();
  await host.close();
}
