import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const read = async path => (await fetch(base + path)).json();
const paths = ['/api/routes', '/api/vault', '/api/patterns', '/api/sessions'];
const initial = await Promise.all(paths.map(read));
const claude = initial[0].find(route => new URL(route.cliUrl || route.incomingUrl).pathname === '/anthropic/v1');
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
await host.isolateClipboard(context);
const page = await context.newPage();
page.setDefaultTimeout(10000);
const writes = [];
const external = [];
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url());
  if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
});
try {
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length > 0);
  assert.equal(await page.getByRole('heading', { name: 'Куда отправлять запросы?', exact: true }).isVisible(), true);
  assert.equal(await page.locator('#firstRunGuide li').first().innerText(), 'Куда отправлять запросы? Выберите получателя ниже.');
  assert.doesNotMatch(await page.locator('#firstRunGuide').innerText(), /сервис модели/);
  assert.match(await page.locator('#overviewRoutes .app-route-columns').innerText(), /Получатель запросов/);
  const actions = page.locator('#overviewRoutes [data-action="route-open"]');
  const index = (await actions.evaluateAll(nodes => nodes.map(node => JSON.parse(node.dataset.args)[0]))).indexOf(claude.id);
  await actions.nth(index).getByRole('button', { name: 'Как подключить', exact: true }).click();
  const nativeDialog = page.getByRole('dialog', { name: 'Подключить приложение · ' + claude.name, exact: true });
  await nativeDialog.waitFor();
  const dialog = page.locator('#connectionSettingsDialog');
  await dialog.getByRole('button', { name: 'Скопировать настройку', exact: true }).waitFor();
  const help = dialog.locator('gv-details[data-detail-id="claude-help.' + claude.id + '"]');
  const address = dialog.locator('gv-details[data-detail-id="client-address.' + claude.id + '"]');
  assert.equal(await help.evaluate(element => element.open), false);
  assert.equal(await address.evaluate(element => element.open), false);
  assert.equal(await dialog.getByRole('link', { name: 'Об авторизации', exact: true }).isVisible(), false);
  assert.equal(await dialog.getByRole('textbox').count(), 0);
  const visible = await dialog.ariaSnapshot();
  assert.match(visible, /Задайте переменную окружения и запустите Claude Code/);
  assert.doesNotMatch(visible, /\$env:|выполните в PowerShell/);
  assert.doesNotMatch(visible, /API key|anthropic-beta|Bearer|OAuth/);
  assert.ok(visible.split(/\s+/).length < 100, 'Default instruction must stay brief');
  assert.equal(await dialog.locator('pre.app-code:visible').count(), 1);
  if (process.env.CLAUDE_EXISTING_AUTH_SCREENSHOT) await nativeDialog.screenshot({ path: process.env.CLAUDE_EXISTING_AUTH_SCREENSHOT });
  const expectedBase = (claude.cliUrl || claude.incomingUrl).replace(/\/v1$/, '');
  await dialog.getByRole('button', { name: 'Скопировать настройку', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'ANTHROPIC_BASE_URL=' + expectedBase);
  assert.equal(await dialog.locator('pre.app-code').first().textContent(), 'ANTHROPIC_BASE_URL=' + expectedBase);
  await dialog.getByRole('button', { name: 'Как задать переменную', exact: true }).click();
  const expected = "$env:ANTHROPIC_BASE_URL = '" + expectedBase + "'\nclaude";
  await dialog.getByRole('button', { name: 'Скопировать пример PowerShell', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(copied, expected);
  assert.equal(copied, await dialog.locator('pre.app-code').nth(1).textContent());
  assert.doesNotMatch(copied, /ANTHROPIC_API_KEY|ANTHROPIC_AUTH_TOKEN|CLAUDE_CODE_OAUTH_TOKEN|Read-Host|throw|&\s*\{|setx|login|logout/);
  await writeFile('../.cache/claude-existing-auth-copy.ps1', copied);
  await help.getByRole('button', { name: 'Проверка и подробности', exact: true }).click();
  await dialog.getByText(/Работа вашей установленной версии и подписки через GhostVault здесь не проверена/).waitFor();
  assert.match(await help.innerText(), /\/status/);
  await dialog.getByRole('link', { name: 'Об авторизации', exact: true }).waitFor();
  await address.getByRole('button', { name: 'Адрес CLI → VAULT', exact: true }).click();
  await dialog.getByRole('button', { name: 'Скопировать адрес CLI → VAULT', exact: true }).click();
  await dialog.getByText('Скопировано.', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), expectedBase);
  assert.equal(await dialog.locator('pre.app-code').count(), 2);
  assert.equal(await dialog.getByRole('textbox').count(), 0);
  assert.deepEqual(await Promise.all(paths.map(read)), initial);
  assert.deepEqual(writes, []);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  if (process.env.CLAUDE_EXISTING_AUTH_REPORT) await writeFile(process.env.CLAUDE_EXISTING_AUTH_REPORT, JSON.stringify({ isolated: true, clipboard: 'browser-memory double', clear_request_destination_choice: true, exact_two_lines: true, default_instruction_snapshot: visible, default_details_closed: true, no_auth_assignment_prompt_or_guard: true, end_to_end_limit_available_on_request: true, address_copy_preserved: true, model_or_client_commands_executed: false, browser_api_writes: writes, external_requests: external, page_errors: errors, all_api_state_unchanged: true }, null, 2));
  console.log('PASS Claude existing-auth text/copy: exactly two routing lines, no key prompt/auth guard, optional alternative, unchanged memory state, no client/cloud execution');
} finally {
  await browser.close();
  await host.close();
}
