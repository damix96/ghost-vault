import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

class InterfaceUiTests {
  host = new UiTestHost();
  errors = [];
  posts = 0;
  out = new URL('../.cache/interface-ui/', import.meta.url);
  screenshot = name => this.page.screenshot({ path: fileURLToPath(new URL(name + '.png', this.out)), fullPage: true, animations: 'disabled' });
  closed = async () => { await this.page.waitForFunction(() => !document.getElementById('secretModal').open); await this.page.locator('#secretForm').waitFor({ state: 'hidden' }); };
  edit = async key => { await this.page.evaluate(key => window.app.openModal(key), key); await this.page.locator('#secretForm').waitFor({ state: 'visible' }); };
  value = text => this.page.locator('#modalValInput textarea').fill(text);
  save = async () => {
    const result = this.page.waitForResponse(response => response.url().endsWith('/api/vault/secret') && response.request().method() === 'POST');
    await this.page.locator('#secretForm gv-action[type="submit"]').click();
    const response = await result;
    assert.equal(response.status(), 200);
    await this.closed();
    return response.json();
  };
  privacy = async hidden => {
    await this.page.locator('#interfaceSettingsBtn').click();
    await this.page.locator('#hideEncrypted').setChecked(hidden);
    await this.page.waitForFunction(hidden => window.app.manualSecrets.some(row => row.key === 'PRIVATE' && (hidden ? row.realValue === undefined : row.realValue !== undefined)), hidden);
    await this.page.evaluate(() => document.getElementById('interfaceSettings').hide());
    await this.page.locator('#hideEncrypted').waitFor({ state: 'hidden' });
  };
  run = async () => {
    await mkdir(this.out, { recursive: true });
    const fetchOriginal = globalThis.fetch;
    globalThis.fetch = async (_url, options) => new Response(JSON.stringify({ choices: [{ message: { role: 'assistant', content: JSON.parse(options.body).messages[0].content + ' — полный ответ ассистента' } }] }), { headers: { 'content-type': 'application/json' } });
    try { await this.host.init(undefined, { targetApiBase: 'http://127.0.0.1:1' }); }
    finally { globalThis.fetch = fetchOriginal; }
    this.vault = this.host.server.getVault();
    this.vault.setManualSecret('ORDINARY', 'ordinary-visible');
    this.base = await this.host.server.listen();
    this.browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    this.context = await this.browser.newContext({ viewport: { width: 1440, height: 1050 } });
    await this.host.isolateClipboard(this.context);
    this.page = await this.context.newPage();
    this.page.on('pageerror', error => this.errors.push(error.message));
    this.page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/vault/secret')) this.posts++; });
    await this.page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    await this.page.goto(this.base + '/dashboard#secrets');
    await this.page.waitForFunction(() => window.app?.manualSecrets.length === 1);
    assert.equal(await this.page.locator('#openProtectedCreateBtn').count(), 0);
    assert.equal(await this.page.locator('#hideEncrypted').isChecked(), false);
    await this.page.locator('#openAddModalBtn').click();
    await this.page.locator('#modalKeyInput input').fill('private');
    await this.value(' private-exact-123 ');
    await this.page.locator('#modalEncryptInput').check();
    await this.screenshot('encrypted-form-desktop');
    const created = await this.save();
    assert.equal(created.secret.key, 'PRIVATE');
    assert.equal(created.secret.isSecret, true);
    assert.equal('realValue' in created.secret, false);
    assert.equal(this.vault.getManualSecrets().find(row => row.key === 'PRIVATE').realValue, ' private-exact-123 ');
    assert.equal(await this.page.locator('#modalValInput').evaluate(node => node.value), '');
    await this.edit('PRIVATE');
    assert.equal(await this.page.locator('#modalValInput textarea').inputValue(), '');
    assert.equal(await this.page.locator('#modalEncryptInput').isChecked(), true);
    assert.equal(await this.page.locator('#modalEncryptInput').isDisabled(), true);
    await this.value('cancelled-private');
    await this.page.locator('#cancelModalBtn').click(); await this.closed();
    assert.equal(await this.page.locator('#modalValInput').evaluate(node => node.value), '');
    await this.edit('PRIVATE');
    await this.value('private-replaced-456');
    assert.equal((await this.save()).secret.alias, created.secret.alias);
    await this.edit('ORDINARY');
    assert.equal(await this.page.locator('#modalEncryptInput').isChecked(), false);
    await this.value('ordinary-draft');
    await this.page.locator('#cancelModalBtn').click(); await this.closed();
    await this.edit('ORDINARY');
    assert.equal(await this.page.locator('#modalValInput textarea').inputValue(), 'ordinary-draft');
    await this.value('ordinary-visible'); await this.save();
    const privateValue = 'private-replaced-456';
    const client = await fetch(this.base + '/v1/chat/completions', { method: 'POST', headers: { 'content-type': 'application/json', 'x-session-id': 'display-session' }, body: JSON.stringify({ messages: [{ role: 'user', content: privateValue + ' ordinary-visible' }] }) });
    assert.ok((await client.text()).includes(privateValue));
    const render = () => this.page.evaluate(async () => { const app = window.app; app.switchMainTab('overview'); app.overview.selectedSession = 'display-session'; app.overview.step = (await app.api.getSession('display-session'))[0]; app.overview.renderConversation(); });
    await render();
    const hint = this.page.locator('.app-request-payload gv-hint').filter({ has: this.page.locator('[data-secret-key="PRIVATE"]') }).first();
    assert.ok((await hint.getAttribute('text')).includes(privateValue));
    assert.ok((await this.page.locator('.app-final-response').innerText()).includes('Ассистент'));
    assert.ok((await this.page.locator('.app-final-response').innerText()).includes(privateValue));
    await this.page.locator('.app-final-response [data-content-mode="full"]').first().click();
    assert.ok((await this.page.locator('.app-final-response').innerText()).includes('полный ответ ассистента'));
    await this.screenshot('visible-diagnostics');
    await this.privacy(true);
    await render();
    const hiddenText = await this.page.locator('#overviewConversation').innerText();
    assert.ok(!hiddenText.includes(privateValue));
    assert.ok(hiddenText.includes('ordinary-visible'));
    assert.ok(await this.page.evaluate(value => !JSON.stringify(window.app.overview.step).includes(value), privateValue));
    await this.page.evaluate(() => { window.app.overview.contentMode = 'changes'; window.app.overview.renderConversation(); });
    assert.ok((await this.page.locator('.app-final-response').innerText()).includes('Значение скрыто'));
    assert.ok((await hint.getAttribute('text')).includes('скрыто настройкой'));
    await this.screenshot('hidden-encrypted-only');
    await this.page.reload();
    await this.page.waitForFunction(() => window.app?.manualSecrets.some(row => row.key === 'PRIVATE'));
    assert.equal(await this.page.locator('#hideEncrypted').isChecked(), true);
    await this.privacy(false);
    await render();
    assert.ok((await this.page.locator('#overviewConversation').innerText()).includes(privateValue));
    await this.page.evaluate(() => window.app.switchMainTab('secrets'));
    await this.edit('PRIVATE');
    await this.value('private-lost-response');
    let committed = false;
    await this.page.route('**/api/vault/secret', async route => { const response = await route.fetch(); assert.equal(response.status(), 200); committed = true; await route.abort('failed'); }, { times: 1 });
    await this.page.locator('#secretForm gv-action[type="submit"]').click();
    await this.page.waitForFunction(() => window.app.modals.review && !window.app.modals.pending.has('secret'));
    assert.ok(committed);
    assert.equal(this.vault.getManualSecrets().find(row => row.key === 'PRIVATE').realValue, 'private-lost-response');
    await this.page.locator('#secretForm gv-action[type="submit"]').click();
    await this.page.waitForFunction(() => !window.app.modals.pending.has('secret') && document.getElementById('secretFormError').message.includes('Список обновлён'));
    assert.equal(this.posts, 4);
    await this.page.locator('#cancelModalBtn').click(); await this.closed();
    assert.equal(await this.page.locator('#modalValInput').evaluate(node => node.value), '');
    await this.page.setViewportSize({ width: 390, height: 844 });
    await this.page.evaluate(() => window.app.switchMainTab('secrets'));
    await this.page.locator('#openAddModalBtn').click();
    await this.page.locator('#modalEncryptInput').check();
    await this.screenshot('encrypted-form-mobile');
    assert.equal(await this.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await this.page.locator('#cancelModalBtn').click(); await this.closed();
    await this.page.locator('#interfaceSettingsBtn').click();
    await this.screenshot('settings-mobile');
    assert.deepEqual(this.errors, []);
    assert.equal(this.posts, 4);
    await writeFile(new URL('result.json', this.out), JSON.stringify({ result: 'PASS', runtime: process.version, browser: this.browser.version(), posts: this.posts, pageErrors: this.errors, checks: ['one form/checkbox', 'real DPAPI create/replace exact value and stable alias', 'protected input clear/ordinary draft', 'visible actual request snapshots and assistant full text', 'only encrypted values hidden', 'preference persists and reverses', 'desktop/mobile'] }, null, 2));
    console.log('PASS unified variable editor and selective interface privacy browser checks');
  };
  close = async () => { await this.browser?.close(); await this.host.close(); };
}

const test = new InterfaceUiTests();
try { await test.run(); } catch (error) { if (test.page) await test.screenshot('failure'); throw error; } finally { await test.close(); }
