import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const read = async path => (await fetch(base + path)).json();
const customResponse = await fetch(base + '/api/routes', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'Isolated unknown client', prefix: 'synthetic-unknown-client', upstreamUrl: 'https://synthetic.invalid/v1' }) });
assert.equal(customResponse.status, 201);
const routes = await read('/api/routes');
const byPath = path => routes.find(route => new URL(route.cliUrl || route.incomingUrl).pathname === path);
const claude = byPath('/anthropic/v1');
const ollama = byPath('/ollama/v1');
const zen = byPath('/opencode/v1');
const go = byPath('/opencode-go/v1');
const unknown = byPath('/synthetic-unknown-client/v1');
const initial = await Promise.all(['/api/vault', '/api/patterns', '/api/sessions'].map(read));
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
await host.isolateClipboard(context);
const page = await context.newPage();
page.setDefaultTimeout(10000);
const writes = [];
const external = [];
const errors = [];
page.on('request', request => {
  if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.method() + ' ' + request.url());
  if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
});
page.on('pageerror', error => errors.push(error.message));
const dialog = page.locator('#connectionSettingsDialog');
const open = async route => {
  const actions = page.locator('#overviewRoutes [data-action="route-open"]');
  const index = (await actions.evaluateAll(nodes => nodes.map(node => JSON.parse(node.dataset.args)[0]))).indexOf(route.id);
  await actions.nth(index).getByRole('button', { name: 'Как подключить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключить приложение · ' + route.name, exact: true }).waitFor();
};
const close = async () => {
  await dialog.getByRole('button', { name: 'Закрыть инструкцию', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
};
const copy = async name => {
  await dialog.getByRole('button', { name, exact: true }).click();
  await page.waitForFunction(() => !document.getElementById('connectionCopyStatus').hidden);
  return page.evaluate(() => navigator.clipboard.readText());
};
try {
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length >= 6);
  await open(claude);
  await dialog.getByRole('button', { name: 'Проверка и подробности', exact: true }).click();
  await dialog.getByRole('button', { name: 'Адрес CLI → VAULT', exact: true }).click();
  const scope = await dialog.innerText();
  assert.match(scope, /ANTHROPIC_BASE_URL/);
  assert.match(scope, /Для Desktop\/claude.ai этот пример не предназначен/);
  assert.match(scope, /Сохранённый вход не перенастраивается/);
  assert.match(scope, /\/status/);
  assert.doesNotMatch(scope, /Скопируйте адрес ниже и укажите его в своём приложении/);
  if (process.env.CLIENT_INSTRUCTIONS_SCREENSHOT) await page.getByRole('dialog', { name: 'Подключить приложение · ' + claude.name, exact: true }).screenshot({ path: process.env.CLIENT_INSTRUCTIONS_SCREENSHOT });
  const claudeBase = (claude.cliUrl || claude.incomingUrl).replace(/\/v1$/, '');
  assert.equal(await copy('Скопировать адрес CLI → VAULT'), claudeBase);
  await dialog.getByRole('button', { name: 'Как задать переменную', exact: true }).click();
  const claudeScript = await copy('Скопировать пример PowerShell');
  assert.equal(claudeScript, await dialog.locator('pre.app-code').nth(1).textContent());
  assert.ok(claudeScript.includes('$env:ANTHROPIC_BASE_URL = ' + "'" + claudeBase + "'"));
  assert.equal(claudeScript.split('\n').length, 2);
  assert.doesNotMatch(claudeScript, /Read-Host|ANTHROPIC_API_KEY|ANTHROPIC_AUTH_TOKEN|CLAUDE_CODE_OAUTH_TOKEN|throw/);
  assert.doesNotMatch(claudeScript, /setx|export |--dangerously|public|\/v1\/v1/);
  await writeFile('../.cache/claude-instructions-copy.ps1', claudeScript);
  await close();
  await open(ollama);
  await dialog.getByRole('button', { name: 'Примеры настройки', exact: true }).click();
  await dialog.getByRole('button', { name: 'Проверочный запрос: PowerShell', exact: true }).click();
  const httpScript = await copy('Скопировать запрос PowerShell');
  assert.equal(httpScript, await dialog.locator('pre.app-code').nth(2).textContent());
  assert.ok(httpScript.includes("$gvBase = '" + (ollama.cliUrl || ollama.incomingUrl) + "'"));
  assert.match(httpScript, /\/models/);
  assert.match(httpScript, /\/chat\/completions/);
  assert.match(httpScript, /Read-Host 'Model ID/);
  assert.match(httpScript, /UTF8.GetBytes/);
  assert.match(await dialog.innerText(), /Этот проверочный запрос обращается к модели/);
  await writeFile('../.cache/openai-instructions-copy.ps1', httpScript);
  await close();
  await open(zen);
  await dialog.getByRole('button', { name: 'Отдельное подключение ghostvault-zen', exact: true }).click();
  const config = JSON.parse(await copy('Скопировать фрагмент plugins'));
  assert.deepEqual(Object.keys(config), ['plugins']);
  assert.equal(config.plugins[0].options.baseURL, zen.cliUrl || zen.incomingUrl);
  assert.equal(config.plugins[0].options.nativeTransport, false);
  await close();
  await open(go);
  assert.match(await dialog.innerText(), /нет проверенной инструкции/);
  assert.equal(await dialog.getByRole('button', { name: 'Скопировать пример PowerShell', exact: true }).count(), 0);
  await close();
  await open(unknown);
  assert.match(await dialog.innerText(), /пока нет инструкции конкретного клиента/);
  assert.equal(await dialog.getByRole('button', { name: 'Скопировать запрос PowerShell', exact: true }).count(), 0);
  await close();
  const changed = await fetch(base + '/api/routes/' + claude.id, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ upstreamUrl: 'https://unverified.synthetic.invalid' }) });
  assert.equal(changed.status, 200);
  await page.getByRole('button', { name: 'Обновить страницу', exact: true }).click();
  await open(claude);
  assert.match(await dialog.innerText(), /Для изменённого адреса сервиса способ входа Claude не подтверждён/);
  assert.equal(await dialog.getByRole('button', { name: 'Скопировать настройку', exact: true }).count(), 0);
  assert.deepEqual(await Promise.all(['/api/vault', '/api/patterns', '/api/sessions'].map(read)), initial);
  assert.equal(await page.getByRole('button', { name: 'Закрепить подсказку', exact: true }).count(), 0);
  assert.deepEqual(writes, []);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  if (process.env.CLIENT_INSTRUCTIONS_REPORT) await writeFile(process.env.CLIENT_INSTRUCTIONS_REPORT, JSON.stringify({ isolated: true, fixture_route_writes: 2, browser_api_writes: writes, external_requests: external, page_errors: errors, clipboard: 'browser-memory double', copied_scripts_equal_display: true, claude_base_has_no_v1_suffix: true, claude_existing_auth_status_explicit: true, powershell_script_files_for_parse_only: ['.cache/claude-instructions-copy.ps1', '.cache/openai-instructions-copy.ps1'], powershell_or_clients_executed: false, zen_plugins_only_preserved: true, go_and_unknown_limits_visible: true, changed_upstream_no_existing_auth_recipe: true, vault_patterns_sessions_unchanged: true, pin_button_default_off: true }, null, 2));
  console.log('PASS concrete client instructions: copied PowerShell text, exact Claude base, Zen preserved, unknown boundaries, no browser writes/cloud/client execution');
} catch (error) {
  console.error(await page.locator('body').ariaSnapshot());
  throw error;
} finally {
  await browser.close();
  await host.close();
}
