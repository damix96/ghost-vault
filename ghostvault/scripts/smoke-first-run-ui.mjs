import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { UiTestHost } from './ui-test-host.mjs';

const host = new UiTestHost();
await host.init();
const base = await host.app.listen({ port: 0, host: '127.0.0.1' });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
await host.isolateClipboard(context);
const page = await context.newPage();
page.setDefaultTimeout(10000);
const writes = [];
const external = [];
const errors = [];
const observe = target => {
  target.on('request', request => {
    if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.method() + ' ' + new URL(request.url()).pathname);
    if (!request.url().startsWith(base) && !request.url().startsWith('data:')) external.push(request.url());
  });
  target.on('pageerror', error => errors.push(error.message));
};
observe(page);
const read = async path => (await fetch(base + path)).json();
const originalRoutes = await read('/api/routes');
const originalPatterns = await read('/api/patterns');
const initialVault = await read('/api/vault');
try {
  assert.equal((await read('/api/sessions')).length, 0);
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => window.app?.overview.routes.length > 0);
  assert.equal(await page.getByRole('heading', { name: 'Подключите приложение к GhostVault', exact: true }).isVisible(), true);
  assert.equal(await page.locator('#firstRunGuide').isVisible(), true);
  assert.equal(await page.locator('#firstRunGuide li').count(), 3);
  assert.equal(await page.locator('#overviewMetrics').isVisible(), false);
  const snapshot = await page.locator('body').ariaSnapshot();
  assert.doesNotMatch(snapshot, /CLI → GhostVault|Наблюдалось|Предустановлено/);
  const columns = await page.locator('#overviewRoutes .app-route-columns').innerText();
  assert.match(columns, /CLI → VAULT/);
  assert.match(columns, /Куда уйдёт запрос/);
  const row = page.locator('#overviewRoutes [role="listitem"]').first();
  assert.equal(await row.getByRole('button').count(), 1, 'Connection row must not have adjacent hint buttons or a fake status action');
  assert.equal(await row.getByText('Запросов пока нет', { exact: true }).isVisible(), true);
  if (process.env.FIRST_RUN_SCREENSHOT) await page.screenshot({ path: process.env.FIRST_RUN_SCREENSHOT, fullPage: true });
  const routeId = JSON.parse(await row.locator('[data-action="route-open"]').getAttribute('data-args'))[0];
  const route = originalRoutes.find(item => item.id === routeId);
  const primary = row.getByRole('button', { name: 'Как подключить', exact: true });
  await primary.hover();
  assert.equal(await row.getByRole('button', { name: 'Закрепить подсказку', exact: true }).count(), 0);
  assert.equal(await row.locator('gv-hint').count(), 0);
  assert.equal(await page.evaluate(() => window.app.connections.editor.isOpen()), false);
  await primary.click();
  await page.getByRole('dialog', { name: 'Подключить приложение · ' + route.name, exact: true }).waitFor();
  const dialog = page.locator('#connectionSettingsDialog');
  assert.match(await dialog.innerText(), /ANTHROPIC_BASE_URL|Base URL|opencode/);
  await dialog.getByRole('button', { name: 'Адрес CLI → VAULT', exact: true }).click();
  assert.equal(await dialog.getByRole('button', { name: 'Скопировать адрес CLI → VAULT', exact: true }).isVisible(), true);
  assert.equal(await dialog.getByRole('textbox', { name: /^Адрес сервиса модели/ }).count(), 0, 'Optional service editing must not obscure first connection instructions');
  await dialog.getByRole('button', { name: 'Скопировать адрес CLI → VAULT', exact: true }).click();
  await page.waitForFunction(() => !document.getElementById('connectionCopyStatus').hidden);
  const originalAddress = route.cliUrl || route.incomingUrl;
  const expectedAddress = new URL(originalAddress).pathname === '/anthropic/v1' ? originalAddress.replace(/\/v1$/, '') : originalAddress;
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), expectedAddress);
  if (process.env.FIRST_RUN_DIALOG_SCREENSHOT) await page.screenshot({ path: process.env.FIRST_RUN_DIALOG_SCREENSHOT, fullPage: true });
  await dialog.getByRole('button', { name: 'Закрыть инструкцию', exact: true }).click();
  await page.waitForFunction(id => [...document.querySelectorAll('#overviewRoutes [data-action="route-open"]')].some(action => JSON.parse(action.dataset.args)[0] === id && action.contains(document.activeElement)), routeId);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await host.isolateClipboard(mobile);
  const mobilePage = await mobile.newPage();
  mobilePage.setDefaultTimeout(10000);
  observe(mobilePage);
  await mobilePage.goto(base + '/dashboard');
  await mobilePage.waitForFunction(() => window.app?.overview.routes.length > 0);
  assert.equal(await mobilePage.locator('#firstRunGuide').isVisible(), true);
  assert.equal(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  assert.equal(await mobilePage.locator('#overviewRoutes [role="listitem"]').first().getByRole('button').count(), 1);
  const mobilePrimary = mobilePage.locator('#overviewRoutes [data-action="route-open"]').first().getByRole('button', { name: 'Как подключить', exact: true });
  await mobilePrimary.scrollIntoViewIfNeeded();
  await mobilePrimary.tap();
  await mobilePage.waitForFunction(() => window.app.connections.editor.isOpen());
  await mobilePage.getByRole('button', { name: 'Закрыть инструкцию', exact: true }).tap();
  await mobilePage.waitForFunction(id => [...document.querySelectorAll('#overviewRoutes [data-action="route-open"]')].some(action => JSON.parse(action.dataset.args)[0] === id && action.contains(document.activeElement)), routeId);
  await mobilePage.locator('gv-hint').evaluateAll(hints => hints.forEach(hint => hint.hide()));
  if (process.env.FIRST_RUN_MOBILE_SCREENSHOT) await mobilePage.screenshot({ path: process.env.FIRST_RUN_MOBILE_SCREENSHOT, fullPage: true });
  await mobile.close();
  const finalVault = await read('/api/vault');
  assert.deepEqual(finalVault.manualSecrets || finalVault.manual || [], initialVault.manualSecrets || initialVault.manual || []);
  assert.deepEqual(finalVault.autoSecrets || finalVault.auto || [], initialVault.autoSecrets || initialVault.auto || []);
  assert.deepEqual(await read('/api/routes'), originalRoutes);
  assert.deepEqual(await read('/api/patterns'), originalPatterns);
  assert.deepEqual(await read('/api/sessions'), []);
  assert.deepEqual(writes, []);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  const report = { scenario: 'clean first use: choose service, find and copy application address, close instructions', isolated: true, clipboard: 'browser-memory double', api_writes: writes, state_unchanged: true, adjacent_hint_buttons: false, preview_pin_button: false, normal_pointer_and_tap: true, redundant_connection_hint: false, desktop_and_mobile: true, page_errors: errors };
  if (process.env.FIRST_RUN_REPORT) await writeFile(process.env.FIRST_RUN_REPORT, JSON.stringify(report, null, 2));
  console.log('PASS first-use copy path, plain language, no adjacent hint controls, mobile layout and unchanged clean state');
} catch (error) {
  console.error(await page.locator('body').ariaSnapshot());
  throw error;
} finally {
  await browser.close();
  await host.close();
}
