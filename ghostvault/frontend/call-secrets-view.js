import { escapeHtml } from './utils.js';
import { Ui } from './ui-components.js';

export class CallSecretsView {
  static render = (step, sent, display) => {
    const counts = sent === undefined ? new Map() : display.counts(sent);
    const touched = (step.interceptedSecrets || []).map(secret => secret.key);
    const keys = [...new Set([...counts.keys(), ...touched])];
    const cards = keys.map(key => {
      const entry = [...display.aliases.values()].find(item => item.secret.key === key);
      const alias = entry?.secret.alias;
      const count = counts.get(key);
      return `<article class="app-substitution"><header><strong>${escapeHtml(key)}</strong><span>${count === undefined ? '?????????? ??? ?????????' : '? ???????: ' + count}</span></header><div class="app-substitution-pair"><div><small>????</small>${entry ? Ui.value(entry.secret.realValue, 'call:' + key, '???????? ????????') : '<p>???????? ?? ?????????</p>'}</div><div><small>? ??????</small>${alias ? '<div class="app-token">' + display.render(alias) + '</div>' + Ui.button('?????????? ???????????', 'secret-copy', [alias], true, '', 'compact') : '<p>??????????? ?? ?????????</p>'}</div></div></article>`;
    }).join('');
    const unknown = [...new Set((JSON.stringify(sent) || '').match(/\$\$\{<[^<>]+>\}/g) || [])].filter(alias => !display.aliases.has(alias));
    return `<section class="app-call-secrets"><h3>???????????</h3>${cards || '<p class="app-help">??????? ?? ???????.</p>'}${unknown.map(alias => '<article class="app-substitution">' + display.render(alias) + '<p class="app-help">???????? ???????? ?? ?????????.</p></article>').join('')}</section>`;
  };
}
