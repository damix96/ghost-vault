import assert from 'node:assert/strict';
import { RuntimeSessions } from './proxy/runtime-sessions.js';
import { SecretRedactor } from './vault/secret-redactor.js';
import { TransactionRecord } from './telemetry/types.js';

const original = 'synthetic-retained-secret';
const redactor = new SecretRedactor();
const runtime = new RuntimeSessions(undefined, undefined, undefined, record => redactor.redact(record));
const timestamp = new Date().toISOString();
const record: TransactionRecord = { id: 'transaction', sessionId: 'session', timestamp, request: { method: 'POST', url: '/v1/messages?secret=' + original, headers: { token: original }, body: { text: original }, client: 'fixture' }, interceptedSecrets: [] };
const call = runtime.begin(record);
const before = runtime.previewRevision();
assert.ok(JSON.stringify(runtime.bySession('session')).includes(original));
redactor.remember([{ value: original, alias: '$${<PROTECTED>}' }]);
runtime.refreshProtection();
assert.throws(() => runtime.preview(0, timestamp, before), { statusCode: 409 });
for (const output of [runtime.records(), runtime.bySession('session'), runtime.find('transaction'), runtime.list(), runtime.preview(0, timestamp)]) assert.equal(JSON.stringify(output).includes(original), false);
const projected = runtime.records()[0];
assert.ok(Object.isFrozen(projected));
assert.ok(Object.isFrozen(projected.request.body));
assert.equal(record.request.body.text, original);
const revision = runtime.previewRevision();
assert.equal(call.update({ ...record, response: { status: 200, headers: {}, body: original, isStream: false, client: 'fixture' } }), true);
assert.equal(runtime.previewRevision(), revision);
assert.equal(JSON.stringify(runtime.bySession('session')).includes(original), false);
const stats = runtime.stats();
assert.equal(runtime.stats().revision, stats.revision);
assert.equal(runtime.stats().bytes, stats.bytes);
call.end();
assert.equal(runtime.list()[0].activeCalls, 0);
assert.equal(runtime.list()[0].state, 'complete');
runtime.clear();
assert.equal(runtime.stats().bytes, 0);
console.log('Protected RAM retention/all readers/preview invalidation/ordinary isolation PASS');
