import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { SecretInputManager } from './secret-input/manager.js';
import { SecretInputBrowser } from './secret-input/browser-launcher.js';
import { SecretInputStorage } from './secret-input/schema.js';

let now = 100;
let launches = 0;
let commits = 0;
let fail = false;
let settle: (() => void) | undefined;
let gate: Promise<void> | undefined;
const secret = ' synthetic exact\r\n秘密 ';
const storage: SecretInputStorage = {
  inspect: (_operation, names) => names.map(name => ({ name, expectedRevision: null })),
  commit: async (_operation, entries) => {
    commits++;
    if (gate) await gate;
    if (fail) throw Object.assign(new Error(secret), { code: 'PROVIDER_UNAVAILABLE' });
    assert.ok(entries.every(entry => entry.value === secret));
    return { variables: entries.map(entry => ({ name: entry.name, token: '$${<' + entry.name + '>}' })) };
  },
};
const manager = new SecretInputManager(storage, new SecretInputBrowser('win32', async () => { launches++; return true; }), () => now);
const first = await manager.request({ operation: 'new', names: ['ONE', 'TWO'], idempotencyKey: 'first' }, 'http://127.0.0.1:12345');
assert.equal(first.state, 'awaiting_input');
assert.equal(first.launch, 'attempted');
assert.deepEqual(await manager.request({ operation: 'new', names: ['TWO', 'ONE'], idempotencyKey: 'first' }, 'http://127.0.0.1:12345'), first);
assert.equal(launches, 1);
await assert.rejects(manager.request({ operation: 'new', names: ['OTHER'], idempotencyKey: 'first' }), { code: 'REQUEST_CONFLICT' });
await assert.rejects(manager.request({ operation: 'new', names: ['ONE'], idempotencyKey: 'busy' }), { code: 'NAME_CONFLICT' });
for (const input of [{ operation: 'new', names: ['bad name'], idempotencyKey: 'invalid' }, { operation: 'new', names: ['DUP', 'DUP'], idempotencyKey: 'dup' }, { operation: 'new', names: [], idempotencyKey: 'none' }]) await assert.rejects(manager.request(input), { code: 'INVALID_INPUT' });
const submissionId = randomUUID();
assert.throws(() => manager.submit(first.requestId, { submissionId, values: [{ name: 'ONE', value: secret }] }), { code: 'REQUEST_CONFLICT' });
assert.throws(() => manager.submit(first.requestId, { submissionId, values: [{ name: 'ONE', value: '' }] }), { code: 'INVALID_INPUT' });
assert.equal(commits, 0);
const completed = await manager.submit(first.requestId, { submissionId, values: ['ONE', 'TWO'].map(name => ({ name, value: secret })) });
assert.equal(completed.state, 'completed');
assert.equal(commits, 1);
assert.equal(JSON.stringify(completed).includes(secret), false);
assert.deepEqual(await manager.submit(first.requestId, { submissionId, values: ['ONE', 'TWO'].map(name => ({ name, value: secret })) }), completed);
assert.equal(commits, 1);
assert.throws(() => manager.submit(first.requestId, { submissionId: randomUUID(), values: [{ name: 'ONE', value: secret }] }), { code: 'REQUEST_CLOSED' });
const cancelled = await manager.request({ operation: 'update', names: ['CANCEL'], idempotencyKey: 'cancel' });
assert.equal(manager.cancel(cancelled.requestId).state, 'cancelled');
assert.equal(manager.cancel(cancelled.requestId).state, 'cancelled');
assert.throws(() => manager.submit(cancelled.requestId, { submissionId: randomUUID(), values: [{ name: 'CANCEL', value: secret }] }), { code: 'REQUEST_CLOSED' });
const expired = await manager.request({ operation: 'new', names: ['EXPIRE'], idempotencyKey: 'expire' });
now = expired.expiresAt;
assert.equal(manager.status(expired.requestId).state, 'expired');
assert.throws(() => manager.submit(expired.requestId, { submissionId: randomUUID(), values: [{ name: 'EXPIRE', value: secret }] }), { code: 'REQUEST_EXPIRED' });
fail = true;
const unavailable = await manager.request({ operation: 'new', names: ['UNAVAILABLE'], idempotencyKey: 'unavailable' });
const failure = await manager.submit(unavailable.requestId, { submissionId: randomUUID(), values: [{ name: 'UNAVAILABLE', value: secret }] });
assert.equal(failure.state, 'failed');
assert.equal(failure.error?.code, 'PROVIDER_UNAVAILABLE');
assert.equal(JSON.stringify(failure).includes(secret), false);
fail = false;
gate = new Promise(resolve => { settle = resolve; });
const pending = await manager.request({ operation: 'new', names: ['PENDING'], idempotencyKey: 'pending' });
const committing = manager.submit(pending.requestId, { submissionId: randomUUID(), values: [{ name: 'PENDING', value: secret }] });
assert.equal(manager.status(pending.requestId).state, 'committing');
assert.throws(() => manager.cancel(pending.requestId), { code: 'COMMIT_IN_PROGRESS' });
now += 600_001;
assert.equal(manager.status(pending.requestId).state, 'committing');
const closing = manager.close();
await assert.rejects(manager.request({ operation: 'new', names: ['CLOSED'], idempotencyKey: 'closed' }), { code: 'INPUT_STOPPING' });
settle!();
assert.equal((await committing).state, 'completed');
await closing;
assert.throws(() => manager.status('unknown'), { code: 'REQUEST_NOT_FOUND' });
const restarted = new SecretInputManager(storage);
assert.throws(() => restarted.status(pending.requestId), { code: 'REQUEST_NOT_FOUND' });
await restarted.close();
console.log('Secret input state/dedup/exact values/failure/drain PASS');
