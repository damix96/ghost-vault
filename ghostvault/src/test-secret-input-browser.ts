import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';
import { chromium } from 'playwright-core';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { SecretInputView } from './secret-input/schema.js';

const stage = path.resolve('.cache/secret-vault-ui');
const evidence = path.resolve('.cache/secret-intake-browser');
mkdirSync(evidence, { recursive: true });
const executablePath = ['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Google/Chrome/Application/chrome.exe'].find(existsSync);
assert.ok(executablePath, 'Installed isolated browser is required');
const child = spawn(process.execPath, [path.resolve('node_modules/tsx/dist/cli.mjs'), path.resolve('src/secret-input/test-browser-fixture.ts')], { stdio: ['pipe', 'pipe', 'pipe'], windowsHide: true });
const lines = createInterface({ input: child.stdout });
const childExit = new Promise<number | null>(resolve => child.once('exit', resolve));
const timeout = setTimeout(() => child.kill(), 90000);
let stderr = '';
child.stderr.on('data', chunk => { stderr += chunk; });
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1200, height: 900 } });
const page = await context.newPage();
page.setDefaultTimeout(10000);
const messages: string[] = [];
page.on('console', message => messages.push(message.type() + ': ' + message.text()));
page.on('pageerror', error => messages.push(error.message));
let client: Client | undefined;
const secrets = [' synthetic-browser-first-input-秘密 ', 'synthetic-browser-second-input', 'synthetic-browser-ordinary-replacement', 'synthetic-browser-new-replacement', 'synthetic-browser-cancelled-input'];
const upstream = createServer((_request, response) => { response.setHeader('content-type', 'application/json'); response.end(JSON.stringify({ choices: [{ message: { role: 'assistant', content: '$${<BROWSER_FIRST>}|$${<BROWSER_SECOND>}' } }] })); });
await new Promise<void>(resolve => upstream.listen(0, '127.0.0.1', resolve));
const responseMetadata: unknown[] = [];
const requestHeaders: Array<Promise<{ path: string; origin?: string; authorization?: string }>> = [];
try {
  const line = await new Promise<string>((resolve, reject) => { lines.once('line', resolve); child.once('error', reject); child.once('exit', code => reject(new Error('Fixture exited before readiness: ' + code))); });
  const fixture = JSON.parse(line) as { origin: string; directory: string };
  await context.route(fixture.origin + '/**', async route => {
    const pathname = new URL(route.request().url()).pathname;
    if (pathname.startsWith('/api/') || pathname === '/mcp') return route.continue();
    const file = pathname === '/' || pathname.startsWith('/vault-secret/') ? path.join(stage, 'index.html') : path.resolve(stage, '.' + decodeURIComponent(pathname));
    if (!file.startsWith(stage + path.sep) || !existsSync(file)) return route.continue();
    const types: Record<string, string> = { '.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.json': 'application/json', '.png': 'image/png', '.woff2': 'font/woff2' };
    await route.fulfill({ status: 200, body: readFileSync(file), contentType: types[path.extname(file)] || 'application/octet-stream', headers: { 'cache-control': 'no-store', 'referrer-policy': 'no-referrer' } });
  });
  page.on('request', request => {
    const pathname = new URL(request.url()).pathname;
    if (pathname.startsWith('/api/secret-input/') && request.method() === 'POST') requestHeaders.push(request.allHeaders().then(headers => ({ path: pathname, origin: headers.origin, authorization: headers.authorization?.split(' ')[0] })));
  });
  client = new Client({ name: 'actual-browser-smoke', version: 'test' });
  await client.connect(new StreamableHTTPClientTransport(new URL('/mcp', fixture.origin), { requestInit: { headers: { authorization: 'Bearer synthetic-browser-fixture-token' } } }));
  const nameFields = page.locator('gv-field[id$="Name"] input');
  const valueFields = page.locator('gv-field[id$="Value"] input');
  const save = page.locator('#secretInputForm gv-action[type="submit"]');
  await page.goto(fixture.origin + '/vault-secret/new');
  await page.locator('#secretInputForm').waitFor({ state: 'visible' });
  await nameFields.nth(0).fill('BROWSER_FIRST');
  await valueFields.nth(0).fill(secrets[0]);
  await page.locator('#secretInputAdd').click();
  await nameFields.nth(1).fill('BROWSER_SECOND');
  await save.click();
  assert.equal(requestHeaders.length, 1);
  await valueFields.nth(1).fill(secrets[1]);
  await save.click();
  await page.locator('#secretInputResult').waitFor({ state: 'visible' });
  await page.screenshot({ path: path.join(evidence, 'direct-result.png'), fullPage: true });
  await page.getByRole('heading', { name: 'Секретные значения сохранены', exact: true }).waitFor();
  assert.equal(await valueFields.count(), 0);
  const catalog = await client.callTool({ name: 'ghostvault_list_variables', arguments: {} });
  responseMetadata.push(catalog);
  assert.ok(JSON.stringify(catalog.structuredContent).includes('BROWSER_FIRST'));
  const upstreamUrl = 'http://127.0.0.1:' + (upstream.address() as { port: number }).port;
  const configured = await fetch(fixture.origin + '/api/routes', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Browser assertion', prefix: 'browser-fixture', upstreamUrl }) });
  assert.equal(configured.status, 201);
  const restored = await fetch(fixture.origin + '/browser-fixture/v1/chat/completions', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ model: 'synthetic', messages: [{ role: 'user', content: 'fixture' }] }) }).then(response => response.json()) as any;
  assert.ok(restored.choices[0].message.content === secrets[0] + '|' + secrets[1], 'Browser values must preserve exact whitespace and Unicode');
  const request = await client.callTool({ name: 'ghostvault_request_secret_input', arguments: { operation: 'update', names: ['SEED_ORDINARY', 'BROWSER_FIRST'], idempotencyKey: randomUUID() } });
  responseMetadata.push(request);
  const view = request.structuredContent as SecretInputView;
  const launch = JSON.parse(readFileSync(path.join(fixture.directory, 'launch.json'), 'utf8')) as { url: string };
  assert.equal(new URL(launch.url).searchParams.get('request'), view.requestId);
  await page.goto(launch.url);
  await page.locator('#secretInputForm').waitFor({ state: 'visible' });
  assert.equal(await valueFields.nth(0).inputValue(), '');
  assert.equal(await valueFields.nth(1).inputValue(), '');
  assert.ok(await nameFields.nth(0).getAttribute('readonly') !== null);
  await valueFields.nth(0).fill(secrets[2]);
  await valueFields.nth(1).fill(secrets[3]);
  await save.click();
  await page.locator('#secretInputResult').waitFor({ state: 'visible' });
  await page.getByRole('heading', { name: 'Секретные значения сохранены', exact: true }).waitFor();
  const status = await client.callTool({ name: 'ghostvault_secret_input_status', arguments: { requestId: view.requestId } });
  responseMetadata.push(status);
  assert.equal((status.structuredContent as SecretInputView).state, 'completed');
  await page.screenshot({ path: path.join(evidence, 'completed.png'), fullPage: true });
  const publicVault = await fetch(fixture.origin + '/api/vault').then(response => response.json()) as any;
  const manual = publicVault.manualSecrets || publicVault.manual;
  assert.ok(manual.some((entry: any) => entry.key === 'SEED_ORDINARY' && entry.isSecret === true && !('realValue' in entry)));
  const cancelRequest = await client.callTool({ name: 'ghostvault_request_secret_input', arguments: { operation: 'new', names: ['BROWSER_CANCEL'], idempotencyKey: randomUUID() } });
  const cancelView = cancelRequest.structuredContent as SecretInputView;
  const cancelLaunch = JSON.parse(readFileSync(path.join(fixture.directory, 'launch.json'), 'utf8')) as { url: string };
  await page.goto(cancelLaunch.url);
  await page.locator('#secretInputForm').waitFor({ state: 'visible' });
  await valueFields.nth(0).fill(secrets[4]);
  await page.locator('#secretInputCancel').click();
  await page.locator('#secretInputResult').waitFor({ state: 'visible' });
  await page.getByRole('heading', { name: 'Ввод отменён', exact: true }).waitFor();
  assert.equal(await valueFields.count(), 0);
  const cancelled = await client.callTool({ name: 'ghostvault_secret_input_status', arguments: { requestId: cancelView.requestId } });
  responseMetadata.push(cancelRequest, cancelled);
  assert.equal((cancelled.structuredContent as SecretInputView).state, 'cancelled');
  const storage = await page.evaluate('JSON.stringify({local:Object.entries(localStorage),session:Object.entries(sessionStorage)})') as string;
  const observedHeaders = await Promise.all(requestHeaders);
  assert.ok(observedHeaders.length >= 6);
  assert.ok(observedHeaders.every(headers => headers.origin === fixture.origin && headers.authorization !== 'Bearer'));
  for (const secret of secrets) for (const output of [JSON.stringify(responseMetadata), JSON.stringify(publicVault), storage, messages.join('\n'), page.url()]) assert.equal(output.includes(secret), false);
  writeFileSync(path.join(evidence, 'result.json'), JSON.stringify({ passed: true, directMultiple: true, partialBlockedBeforeRequest: true, exactWhitespaceUnicodeThroughProxy: true, linkedUpdateOrdinary: true, cancellation: true, inputsCleared: true, storageClean: true, browserWritesHaveOrigin: true, apiCalls: observedHeaders.length, consoleMessages: messages }, null, 2));
  console.log('Actual staged UI + real source/native DB/MCP multi-input/update/cancel/privacy PASS');
} finally {
  await client?.close();
  await context.close();
  await browser.close();
  await new Promise<void>(resolve => upstream.close(() => resolve()));
  child.stdin.end('close\n');
  assert.equal(await childExit, 0);
  clearTimeout(timeout);
  lines.close();
  assert.equal(stderr, '');
}
