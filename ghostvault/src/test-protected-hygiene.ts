import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readFileSync, existsSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { VaultDatabase } from './vault/sqlite-db.js';
import { VaultStore } from './vault/store.js';
import { GhostProxyServer } from './proxy/server.js';

class HygieneTests {
  private directory = path.resolve('.cache/secret-storage-dist/hygiene', randomUUID());
  private file = path.join(this.directory, 'vault.db');
  private values = ['synthetic-past-' + randomUUID() + '/\u5bc6\u78bc', 'synthetic-current-' + randomUUID() + '\r\nline'];
  private forms = (): string[] => [...new Set(this.values.flatMap(value => Object.values(VaultStore.computeVariants(value))))];
  private clean = (text: string): void => { for (const form of this.forms()) assert.equal(text.includes(form), false, 'Diagnostic or file retained synthetic original'); };

  public run = async (): Promise<void> => {
    if (process.platform !== 'win32') { console.log('SKIP real Windows hygiene test'); return; }
    mkdirSync(this.directory, { recursive: true });
    let db = new VaultDatabase(this.file);
    const row = { key: 'HYGIENE', alias: '$${<HYGIENE>}', real_value: this.values[0], mask_in_ai: 1, description: 'Synthetic history', created_at: '2026-01-01', updated_at: '2026-01-02' };
    db.upsertSecret(row);
    db.archiveSecret(row.key);
    db.upsertSecret({ ...row, real_value: this.values[1] });
    let vault = new VaultStore(db);
    const observer = new DatabaseSync(this.file);
    const insert = observer.prepare('INSERT INTO transactions(id, session_id, client, timestamp, prompt_text, masked_prompt, model_response, intercepted_secrets, url, target_url) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)');
    for (const id of ['FIRST', 'FAIL']) insert.run(id, 'public-session', 'public-client', '2026-01-03', this.values[0], this.values[1], this.forms().join('\n'), JSON.stringify([{ key: row.key, alias: row.alias, realValue: this.values[0] }, { key: row.key, realValue: this.values[1] }]), '/route/' + encodeURIComponent(this.values[1]), 'https://synthetic.invalid/' + Buffer.from(this.values[0]).toString('base64'));
    db.setSetting('ordinary_setting', 'unchanged-setting');
    const before = JSON.stringify(observer.prepare('SELECT * FROM transactions').all());
    observer.exec("CREATE TRIGGER synthetic_diagnostic_failure BEFORE UPDATE ON transactions WHEN OLD.id = 'FAIL' BEGIN SELECT RAISE(ABORT, 'synthetic diagnostic failure'); END;");
    assert.throws(() => vault.protectManualSecret(row.key), /synthetic diagnostic failure/);
    assert.equal(JSON.stringify(observer.prepare('SELECT * FROM transactions').all()), before);
    assert.equal(db.getSecrets()[0].is_secret, 0);
    assert.equal(db.getVersions()[0].is_secret, 0);
    assert.equal(db.protectedStorage.cleanupPending, false);
    assert.equal(vault.getManualSecrets()[0].isSecret, false);
    observer.exec('DROP TRIGGER synthetic_diagnostic_failure');
    observer.exec('BEGIN');
    assert.equal((observer.prepare('SELECT real_value FROM secrets WHERE key = ?').get(row.key) as { real_value: string }).real_value, this.values[1]);
    let server = new GhostProxyServer(vault, { port: 0 });
    let app = server.getApp();
    const marked = await app.inject({ method: 'PATCH', url: '/api/vault/secret/HYGIENE', payload: { isSecret: true } });
    assert.equal(marked.statusCode, 200);
    assert.equal(marked.json().success, true);
    assert.equal(marked.json().notice.code, 'SECRET_STORAGE_CLEANUP_PENDING');
    assert.equal(marked.json().secret.isSecret, true);
    this.clean(marked.body);
    assert.equal((await app.inject({ url: '/api/vault' })).json().retention.cleanupPending, true);
    const reading = new DatabaseSync(this.file);
    const diagnostics = reading.prepare('SELECT * FROM transactions ORDER BY id').all();
    this.clean(JSON.stringify(diagnostics));
    assert.equal(diagnostics.length, 2);
    assert.equal(diagnostics[0].id, 'FAIL');
    assert.equal(diagnostics[0].session_id, 'public-session');
    assert.equal(diagnostics[0].client, 'public-client');
    assert.equal(diagnostics[0].timestamp, '2026-01-03');
    assert.equal(db.getSetting('ordinary_setting'), 'unchanged-setting');
    assert.equal(db.protectedStorage.decode(db.getVersions()[0]).real_value, this.values[0]);
    const batch = vault.commitProtectedManualBatch({ requestId: 'synthetic-busy-batch', entries: [{ name: 'NEW_PROTECTED', value: 'synthetic-new-protected-value', expectedRevision: null }] });
    assert.equal(batch.variables[0].token, '$${<NEW_PROTECTED>}');
    assert.equal(batch.notice?.code, 'SECRET_STORAGE_CLEANUP_PENDING');
    assert.equal(db.getSetting('secret_storage_cleanup_pending'), 'purge');
    reading.close();
    await server.close();
    db.close();
    db = new VaultDatabase(this.file);
    vault = new VaultStore(db);
    assert.equal(vault.getRetention().cleanupPending, true);
    assert.equal(vault.unmaskInboundText(row.alias), this.values[1]);
    observer.exec('ROLLBACK');
    observer.close();
    server = new GhostProxyServer(vault, { port: 0 });
    app = server.getApp();
    const next = await app.inject({ method: 'POST', url: '/api/vault/secret', payload: { key: 'ORDINARY', realValue: 'ordinary-after-reader-release' } });
    assert.equal(next.statusCode, 200);
    assert.equal(next.json().notice, undefined);
    assert.equal(vault.getRetention().cleanupPending, false);
    assert.equal(db.getSetting('secret_storage_cleanup_pending'), '');
    for (const file of [this.file, this.file + '-wal']) if (existsSync(file)) this.clean(readFileSync(file).toString('utf8'));
    await server.close();
    db.close();
    const reopened = new VaultDatabase(this.file);
    assert.equal(reopened.protectedStorage.cleanupPending, false);
    reopened.close();
    console.log(JSON.stringify({ protectedHygiene: 'PASS', transactionalDiagnostics: true, sqlRollback: true, busyReaderCommittedNotice: true, batchNotice: true, pendingSurvivesRestart: true, retryNextWrite: true, dbWalCanaryAbsent: true, metadataPreserved: true, fixture: this.directory }));
  };
}

await new HygieneTests().run();
